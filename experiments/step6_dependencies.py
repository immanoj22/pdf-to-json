"""Reproducible read-only audit of Step 6 distributions and bundled license notices.

Copies notices from the active installation into this repository, and fingerprints every
installed distribution record except generated bytecode. It does not install anything or
read any reference-project environment.
"""

from __future__ import annotations

import hashlib
import json
import platform
from importlib.metadata import distribution
from pathlib import Path

from reference_paths import PROJECT_ROOT

PACKAGES = {
    "lingua-language-detector": {
        "scope": "default CPU runtime",
        "license": "Apache-2.0",
        "upstream_license": "https://github.com/pemistahl/lingua-py/blob/main/LICENSE.txt",
    },
    "RapidFuzz": {
        "scope": "default CPU runtime",
        "license": "MIT",
        "upstream_license": "https://github.com/rapidfuzz/RapidFuzz/blob/main/LICENSE",
    },
    "langid": {
        "scope": "comparison only; not required by the converter runtime",
        "license": "BSD-2-Clause",
        "upstream_license": "https://github.com/saffsd/langid.py/blob/master/LICENSE",
        "upstream_notice_url": "https://raw.githubusercontent.com/saffsd/langid.py/master/LICENSE",
        "upstream_notice_sha256": (
            "0ac0db61303964301835be939ef8628f806f681750fd232e21da2cad456a102e"
        ),
    },
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def audit_package(name: str, policy: dict) -> dict:
    package = distribution(name)
    metadata = package.metadata
    declared_files = metadata.get_all("License-File") or []
    files, notices = [], []
    target_directory = PROJECT_ROOT / "docs/licenses/step6" / name.lower()
    for relative in sorted(package.files or (), key=str):
        source = Path(package.locate_file(relative))
        if not source.is_file() or source.suffix == ".pyc":
            continue
        content = source.read_bytes()
        digest = sha256(content)
        row = {"path": str(relative).replace("\\", "/"), "bytes": len(content), "sha256": digest}
        files.append(row)
        basename = source.name.lower()
        is_notice = basename.startswith(
            ("license", "licence", "copying", "notice")
        ) or basename in {Path(entry).name.lower() for entry in declared_files}
        if not is_notice:
            continue
        # A distribution record can contain parent references for entry points. Only the
        # basename is used for copied notices, keeping every destination under this root.
        target_directory.mkdir(parents=True, exist_ok=True)
        target = target_directory / source.name
        if target.exists() and target.read_bytes() != content:
            target = target_directory / f"{digest[:12]}-{source.name}"
        target.write_bytes(content)
        notices.append(
            {
                **row,
                "origin": "installed_distribution",
                "copied_to": target.relative_to(PROJECT_ROOT).as_posix(),
            }
        )
    installed_notices = len(notices)
    if not notices:
        url = policy.get("upstream_notice_url")
        expected = policy.get("upstream_notice_sha256")
        if not url or not expected:
            raise ValueError(f"{name}: no installed or audited upstream license notice")
        target_directory.mkdir(parents=True, exist_ok=True)
        target = target_directory / "UPSTREAM_LICENSE"
        if target.exists():
            content = target.read_bytes()
        else:
            from urllib.request import urlopen

            with urlopen(url) as response:
                content = response.read()
        if sha256(content) != expected:
            raise ValueError(f"{name}: audited upstream license checksum differs")
        target.write_bytes(content)
        notices.append(
            {
                "path": url,
                "origin": "upstream_license_unbundled",
                "bytes": len(content),
                "sha256": expected,
                "copied_to": target.relative_to(PROJECT_ROOT).as_posix(),
            }
        )
    inventory = json.dumps(files, sort_keys=True, separators=(",", ":")).encode()
    metadata_path = next(
        (row for row in files if row["path"].endswith(".dist-info/METADATA")), None
    )
    return {
        "name": metadata["Name"],
        "version": package.version,
        **policy,
        "copyleft": False,
        "declared_license": metadata.get("License"),
        "declared_license_expression": metadata.get("License-Expression"),
        "license_classifiers": [
            value
            for value in metadata.get_all("Classifier") or []
            if value.startswith("License ::")
        ],
        "declared_license_files": declared_files,
        "requires_dist": metadata.get_all("Requires-Dist") or [],
        "installed_recorded_file_count": len(files),
        "installed_recorded_bytes": sum(row["bytes"] for row in files),
        "record_inventory_sha256": sha256(inventory),
        "metadata_file": metadata_path,
        "installed_license_notice_count": installed_notices,
        "license_files": notices,
        "files": files,
    }


def main():
    report = {
        "environment": {"python": platform.python_version(), "platform": platform.platform()},
        "audit_script_sha256": sha256(Path(__file__).read_bytes()),
        "method": (
            "Installed distribution METADATA, recorded file bytes and SHA-256; "
            "generated bytecode excluded"
        ),
        "installation_performed": False,
        "new_copyleft_candidates": [],
        "packages": [audit_package(name, policy) for name, policy in PACKAGES.items()],
        "limitations": [
            "Recorded installed sizes are environment-specific and are not compressed wheel sizes.",
            "License inventory records notices shipped in these installed distributions.",
            "Model data is bundled in Lingua's compiled extension "
            "and included in its file fingerprints.",
            "langid omits its license notice from installed RECORD; "
            "the audited upstream notice is preserved separately with its SHA-256.",
            "langid reuses the existing NumPy dependency, audited in earlier steps.",
        ],
    }
    output = PROJECT_ROOT / "experiments/out/step6/dependencies.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes((json.dumps(report, ensure_ascii=False, indent=2) + "\n").encode())
    print(
        json.dumps(
            [
                {
                    k: row[k]
                    for k in (
                        "name",
                        "version",
                        "license",
                        "scope",
                        "installed_recorded_bytes",
                        "record_inventory_sha256",
                    )
                }
                for row in report["packages"]
            ],
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
